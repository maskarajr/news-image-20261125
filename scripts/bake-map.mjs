import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const converted = feature(topology, topology.objects.land);
const geo = converted.type === 'FeatureCollection' ? converted.features[0].geometry : converted.geometry;
const LAT_MIN = -60, LAT_MAX = 75;

function intersectLatitude(a, b, latitude) {
  const t = (latitude - a[1]) / (b[1] - a[1]);
  return [a[0] + (b[0] - a[0]) * t, latitude];
}

function clipEdge(points, latitude, keepAbove) {
  const output = [];
  for (let i = 0; i < points.length; i++) {
    const current = points[i], previous = points[(i + points.length - 1) % points.length];
    const currentInside = keepAbove ? current[1] >= latitude : current[1] <= latitude;
    const previousInside = keepAbove ? previous[1] >= latitude : previous[1] <= latitude;
    if (currentInside !== previousInside) output.push(intersectLatitude(previous, current, latitude));
    if (currentInside) output.push(current);
  }
  return output;
}

function clipLongitude(points, longitude, keepRight) {
  const output = [];
  for (let i = 0; i < points.length; i++) {
    const current = points[i], previous = points[(i + points.length - 1) % points.length];
    const currentInside = keepRight ? current[0] >= longitude : current[0] <= longitude;
    const previousInside = keepRight ? previous[0] >= longitude : previous[0] <= longitude;
    if (currentInside !== previousInside) {
      const t = (longitude - previous[0]) / (current[0] - previous[0]);
      output.push([longitude, previous[1] + (current[1] - previous[1]) * t]);
    }
    if (currentInside) output.push(current);
  }
  return output;
}

function splitDateline(points) {
  const unwrapped = [points[0].slice()];
  for (let i = 1; i < points.length; i++) {
    let lon = points[i][0];
    const previous = unwrapped.at(-1)[0];
    while (lon - previous > 180) lon -= 360;
    while (lon - previous < -180) lon += 360;
    unwrapped.push([lon, points[i][1]]);
  }
  const pieces = [];
  for (let shift = -2; shift <= 2; shift++) {
    const shifted = unwrapped.map(([lon, lat]) => [lon + shift * 360, lat]);
    const min = Math.min(...shifted.map((point) => point[0])), max = Math.max(...shifted.map((point) => point[0]));
    if (max < -180 || min > 180) continue;
    const clipped = clipLongitude(clipLongitude(shifted, -180, true), 180, false);
    if (clipped.length >= 3) pieces.push(clipped);
  }
  return pieces;
}

function cleanRing(ring) {
  let points = ring.slice(0, ring.length > 1 && ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1] ? -1 : undefined);
  if (points.every((point) => point[1] < LAT_MIN) || points.every((point) => point[1] > LAT_MAX)) return [];
  points = clipEdge(clipEdge(points, LAT_MIN, true), LAT_MAX, false);
  return splitDateline(points).map((piece) => {
    const rounded = [];
    for (const [lon, lat] of piece) {
      const point = [Math.round(lon * 10) / 10, Math.round(Math.max(LAT_MIN, Math.min(LAT_MAX, lat)) * 10) / 10];
      const previous = rounded.at(-1);
      if (!previous || previous[0] !== point[0] || previous[1] !== point[1]) rounded.push(point);
    }
    if (rounded.length > 2 && rounded[0][0] === rounded.at(-1)[0] && rounded[0][1] === rounded.at(-1)[1]) rounded.pop();
    return rounded;
  }).filter((piece) => piece.length >= 3);
}

const polygons = geo.type === 'MultiPolygon' ? geo.coordinates : [geo.coordinates];
const rings = polygons.flatMap((polygon) => cleanRing(polygon[0]));
const output = `// Generated by scripts/bake-map.mjs from Natural Earth via world-atlas.\n// Natural Earth data is public domain. Coordinates are clipped to 60S-75N and rounded to 0.1 degrees.\nexport const WORLD_LAND = ${JSON.stringify(rings)} as const;\n`;
const destination = resolve('world-land.ts');
writeFileSync(destination, output);
console.log(`Wrote ${destination}: ${rings.length} rings, ${rings.reduce((sum, ring) => sum + ring.length, 0)} points`);
